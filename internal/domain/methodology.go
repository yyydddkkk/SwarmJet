package domain

import "time"

// Round-4 contract (docs/claude/round4-prompts.md). A Hive's methodology
// decides how its swarm works; the platform stores it, delivers it to Cells
// and enforces what it declares. Change these declarations only by adding.

// MessageTrust records where a message's content came from, so an Agent can
// tell its user's words from text an outsider wrote on GitHub.
type MessageTrust string

const (
	TrustUser     MessageTrust = "user"     // a local Agent or the console, acting for the user
	TrustAgent    MessageTrust = "agent"    // another Agent in the Hive
	TrustExternal MessageTrust = "external" // derived from third-party content such as GitHub events
	TrustSystem   MessageTrust = "system"   // generated by the platform itself
)

// Methodology is one immutable version of a Hive's methodology. A change is a
// new version; rollback activates an older one.
type Methodology struct {
	ID        string              `json:"id"`
	HiveID    string              `json:"hiveId"`
	Version   int                 `json:"version"`
	Active    bool                `json:"active"`
	Source    *MethodologySource  `json:"source,omitempty"`
	Manifest  MethodologyManifest `json:"manifest"`
	Digest    string              `json:"digest"` // sha256 over the manifest and every file
	Note      string              `json:"note,omitempty"`
	CreatedBy Address             `json:"createdBy"`
	CreatedAt time.Time           `json:"createdAt"`
}

// MethodologySource names the upstream a version was compiled from.
type MethodologySource struct {
	URL  string `json:"url"`            // git repository
	Ref  string `json:"ref"`            // tag, branch or commit as requested
	Path string `json:"path,omitempty"` // directory inside the repository
	SHA  string `json:"sha,omitempty"`  // resolved commit
}

// MethodologyFile is one file of a version, delivered read-only into every
// Cell's CLI configuration directory at the same relative path.
type MethodologyFile struct {
	Path    string `json:"path"` // relative, slash-separated, no ".."
	Content string `json:"content"`
}

// MethodologyManifest is methodology.yaml, the part the platform enforces.
type MethodologyManifest struct {
	DefaultRole    string          `json:"defaultRole"` // role for Agents spawned without one
	Roles          map[string]Role `json:"roles"`
	StandingOrders []string        `json:"standingOrders,omitempty"` // injected into every turn
	Events         []EventRule     `json:"events,omitempty"`
	Merge          MergePolicy     `json:"merge"`
	Limits         Limits          `json:"limits,omitempty"` // zero values keep HiveConfig defaults
	// Round 5. Queen tunes the Hive's Queen. The Queen's existence and core
	// duties are fixed by the platform; a methodology only adds style.
	Queen QueenStyle `json:"queen,omitempty"`
}

// QueenStyle is the part of a methodology that adjusts the Queen. It cannot
// remove the Queen or its core duties (managing the methodology, routing
// work, answering Agents).
type QueenStyle struct {
	Prompt string `json:"prompt,omitempty"` // methodology file appended after the platform's core Queen prompt
	Merge  bool   `json:"merge,omitempty"`  // the Queen may call merge_pr, subject to the merge policy
}

// MethodologyTemplate is one entry of the platform's built-in catalog. A
// template is only an option: no Hive gets it unless the user (usually
// through the Queen) installs it.
type MethodologyTemplate struct {
	Name        string `json:"name"` // e.g. "pstack"
	Title       string `json:"title"`
	Description string `json:"description"` // what kind of team it sets up, in one paragraph
	Version     string `json:"version"`     // template revision shipped with this platform build
}

// Role is one kind of Agent in the swarm.
type Role struct {
	Description string          `json:"description,omitempty"`
	Prompt      string          `json:"prompt,omitempty"`    // path of a methodology file appended to the system prompt
	Model       string          `json:"model,omitempty"`     // provider/model; empty uses the Hive default
	Lifecycle   string          `json:"lifecycle,omitempty"` // "task" (default): ends with its task; "resident": stays
	Permissions RolePermissions `json:"permissions"`
	DenyTools   []string        `json:"denyTools,omitempty"` // CLI tools blocked in this role's Cell
}

// RolePermissions are enforced by the platform, never by the prompt alone.
type RolePermissions struct {
	Publish     bool     `json:"publish"`         // push its branch and open or update its PR
	Message     bool     `json:"message"`         // send to other Agents in the Hive
	Spawn       []string `json:"spawn,omitempty"` // roles it may spawn; empty means none
	Attest      bool     `json:"attest"`          // record attestations
	Merge       bool     `json:"merge"`           // call the merge entry
	Methodology bool     `json:"methodology"`     // publish new methodology versions
}

// EventRule routes an external event to a new or existing Agent of a role.
type EventRule struct {
	Event         string `json:"event"` // issue_labeled, issue_comment, pr_head, check_failed, ...
	Label         string `json:"label,omitempty"`
	CommentPrefix string `json:"commentPrefix,omitempty"`
	Role          string `json:"role"`
}

// MergePolicy is checked by the merge entry before any merge.
type MergePolicy struct {
	RequireAttestation bool           `json:"requireAttestation"`
	AcceptResults      []AttestResult `json:"acceptResults,omitempty"` // default pass, pass_notes
	RequireNonAuthor   bool           `json:"requireNonAuthor"`        // the attester must not be the revision's author
	RequireChecks      bool           `json:"requireChecks"`           // GitHub required checks must pass
	Auto               bool           `json:"auto"`                    // merge as soon as the policy holds
	Method             string         `json:"method,omitempty"`        // squash (default), merge or rebase
}

// Limits overrides HiveConfig limits; the platform never allows "unlimited".
type Limits struct {
	MaxConcurrentAgents int     `json:"maxConcurrentAgents,omitempty"`
	MaxHops             int     `json:"maxHops,omitempty"`
	MaxAgentsPerChain   int     `json:"maxAgentsPerChain,omitempty"`
	MaxCostPerAgentUSD  float64 `json:"maxCostPerAgentUsd,omitempty"`
	MaxCostPerDayUSD    float64 `json:"maxCostPerDayUsd,omitempty"`
}

// AttestResult is an Agent's conclusion about one revision.
type AttestResult string

const (
	AttestPass      AttestResult = "pass"
	AttestPassNotes AttestResult = "pass_notes"
	AttestFail      AttestResult = "fail"
	AttestBlocked   AttestResult = "blocked" // could not finish; never a pass
)

// Attestation is keyed by PR and head commit; a new head supersedes it.
type Attestation struct {
	ID         string       `json:"id"`
	HiveID     string       `json:"hiveId"`
	PRNumber   int64        `json:"prNumber"`
	HeadSHA    string       `json:"headSha"`
	AttesterID string       `json:"attesterId"`
	AuthorID   string       `json:"authorId"` // the Agent that owns the PR branch
	IsAuthor   bool         `json:"isAuthor"` // AttesterID == AuthorID
	Result     AttestResult `json:"result"`
	Summary    string       `json:"summary"`
	Findings   []Finding    `json:"findings,omitempty"`
	CommentURL string       `json:"commentUrl,omitempty"`
	Superseded bool         `json:"superseded"`
	CreatedAt  time.Time    `json:"createdAt"`
}

// Finding is one problem an attester can show with evidence.
type Finding struct {
	Severity string `json:"severity"` // critical, warning or nit
	Location string `json:"location,omitempty"`
	Finding  string `json:"finding"`
	Evidence string `json:"evidence,omitempty"`
}
