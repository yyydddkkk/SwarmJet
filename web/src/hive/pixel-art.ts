// Pixel art for the Hive console (ADR section 18, "pixel accents").
//
// Every sprite is authored on a fixed integer grid, one character per pixel, so
// the shapes stay crisp as long as they are drawn at an integer multiple of the
// grid. ASCII is the source of truth here: it reviews and diffs far better than
// a list of rectangles would.
//
//   .  transparent     #  ink (outline, stripes, eyes, antennae)
//   y  body            d  body shade        i  highlight (eye shine)
//   w  wing            W  wing highlight    b  wing edge
//   p  blush           g  gold              G  gold shade
//
// Colours resolve through the --hg-px-* tokens in hive-console.css, so light and
// dark surfaces stay a stylesheet concern and never leak into the artwork.
import type { IconName } from "./icons";

export type PixelSprite = { grid: number; rows: string[] };

/** Splits ASCII rows into a pixel grid, padding every row to the same width. */
export function art(source: string): string[] {
  const rows = source
    .replace(/^\n/, "")
    .replace(/\s+$/, "")
    .split("\n")
    .map(row => row.trimEnd());
  const width = Math.max(...rows.map(row => row.length));
  return rows.map(row => row.padEnd(width, "."));
}

