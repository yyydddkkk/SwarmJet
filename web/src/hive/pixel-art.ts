function centreIcon(rows: string[]): string[] {
  const width = Math.max(...rows.map(row => row.length));
  const top = Math.floor((16 - rows.length) / 2);
  const left = Math.floor((16 - width) / 2);
  const pad = ".".repeat(left);
  const blank = ".".repeat(16);
  return [
    ...Array.from({ length: top }, () => blank),
    ...rows.map(row => (pad + row).padEnd(16, ".")),
    ...Array.from({ length: 16 - top - rows.length }, () => blank),
  ];
}

